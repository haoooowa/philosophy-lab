import { readFileSync, writeFileSync } from 'fs';
let c = readFileSync('src/data/experiments.js', 'utf8');

function expand(expId, newBg, newScenario) {
  const start = c.indexOf('id: "' + expId + '"');
  if (start === -1) { console.log('NF:', expId); return; }
  const esc = (s) =>
    s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n');
  const bgStart = c.indexOf('body: "', c.indexOf('background:', start)) + 7;
  const bgEnd = c.indexOf('"', bgStart);
  c = c.substring(0, bgStart) + esc(newBg) + c.substring(bgEnd);
  const scStart = c.indexOf('scenario: "', c.indexOf('description:', start)) + 11;
  const scEnd = c.indexOf('"', scStart);
  c = c.substring(0, scStart) + esc(newScenario) + c.substring(scEnd);
  console.log('OK:', expId);
}

